-- 0104: users.sessions_revoked_at — 세션 폐기 시각. (2026-08-26, 역할 모델 v2 티켓 30)
--
-- 슈퍼어드민 재설정·상태 전이는 대상의 모든 세션을 지운다. 그런데 이미 진행 중이던 로그인은
-- 옛 해시를 이미 읽어둔 상태라, 폐기가 커밋된 **뒤에** 세션을 INSERT 할 수 있다. 그 세션은
-- 계정이 active 라 실제로 쓸 수 있어 "전이가 끝나면 세션이 전부 폐기돼 있다" 는 계약이 깨진다.
--
-- 이 컬럼은 그 경합을 잡는 표식이다. 로그인 시작 시점에 이 값을 읽어두고(R0), 세션을 만들기
-- 직전에 다시 읽어(R1) 다르면 그 사이 폐기가 일어난 것이므로 세션 생성을 취소한다.
--
-- 시각 비교가 아니라 **같은 컬럼의 두 번 읽기**인 것이 핵심이다. 앱 서버와 DB 의 시계가
-- 어긋나도 판정이 흔들리지 않는다 — 값이 바뀌었는지만 보기 때문이다.
--
-- nullable 추가라 2단계 배포 규칙(앱 생성값 NOT NULL) 대상이 아니다. 값이 NULL 이면
-- "폐기된 적 없음" 이고, 그 경우 R0 = R1 = NULL 이라 비교가 그대로 성립한다.

BEGIN;

ALTER TABLE "users" ADD COLUMN "sessions_revoked_at" timestamptz;

COMMENT ON COLUMN "users"."sessions_revoked_at" IS
  '이 계정의 세션이 마지막으로 일괄 폐기된 시각 (재설정·상태 전이). 로그인 경합 판정용 표식이며 시각 자체보다 값이 바뀌었는지가 중요하다';

COMMIT;
