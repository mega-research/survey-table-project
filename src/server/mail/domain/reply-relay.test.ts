describe('buildRelayMail — 담당자의 답장을 응답자에게 넘기는 메일', () => {
  const STAFF_REPLY: ReceivedReply = {
    senderAddress: 'lee@example.co.kr',
    senderName: '이담당',
    replyTo: [],
    subject: 'RE: 설문지 회신',
    html: '<p>확인했습니다 <img src="cid:sign@corp"></p>',
    text: '확인했습니다',
    attachments: [
      { filename: 'sign.png', mimeType: 'image/png', contentId: '<sign@corp>', related: true, contentBase64: 'UE5H' },
      { filename: 'guide.pdf', mimeType: 'application/pdf', contentId: null, contentBase64: 'JVBERg==' },
    ],
  };

  const build = (overrides: Partial<Parameters<typeof buildRelayMail>[0]> = {}) =>
    buildRelayMail({
      reply: STAFF_REPLY,
      senderAccount: 'survey',
      sendDomain: SEND_DOMAIN,
      respondentAddress: 'kim@corp.co.kr',
      ...overrides,
    });

  it('받는 사람은 언제나 응답자 한 명이다 — 여럿을 한 통에 넣을 길이 없다', () => {
    expect(build({ respondentAddress: 'park@other.co.kr' }).to).toEqual(['park@other.co.kr']);
  });

  it('받는 사람은 응답자, 보낸 사람은 담당자 이름 + 보낸이 계정(중계 꼬리 없음), 답장 주소는 담당자 주소다', () => {
    expect(build()).toEqual({
      from: '이담당 <survey@send.example.co.kr>',
      to: ['kim@corp.co.kr'],
      replyTo: ['lee@example.co.kr'],
      subject: 'RE: 설문지 회신',
      html: '<p>확인했습니다 <img src="cid:sign@corp"></p>',
      text: '확인했습니다',
      attachments: [
        { filename: 'sign.png', content: 'UE5H', contentType: 'image/png', contentId: 'sign@corp' },
        { filename: 'guide.pdf', content: 'JVBERg==', contentType: 'application/pdf' },
      ],
      headers: { 'X-Survey-Reply-Forward': '1' },
      tags: [{ name: 'kind', value: 'reply-relay' }],
    });
  });

  it('Auto-Submitted 는 붙이지 않는다 — 사람이 쓴 답장이다', () => {
    expect(Object.keys(build().headers).map((key) => key.toLowerCase())).not.toContain('auto-submitted');
  });

  it('받은 메일에 답장 주소가 따로 있으면 그것을 쓴다', () => {
    expect(build({ reply: { ...STAFF_REPLY, replyTo: ['team@example.co.kr'] } }).replyTo).toEqual(['team@example.co.kr']);
  });

  it('담당자가 이름 없이 보냈으면 보낸 사람 이름 자리에 담당자 주소를 쓴다', () => {
    expect(build({ reply: { ...STAFF_REPLY, senderName: null } }).from).toBe(
      '"lee@example.co.kr" <survey@send.example.co.kr>',
    );
  });

  it('첨부를 뺄 때 안내는 응답자에게 하는 말이다 — 발송 서비스의 수신 목록을 말하지 않는다', () => {
    const mail = build({ omitAttachments: true });

    expect(mail.attachments).toEqual([]);
    for (const body of [String(mail.html), String(mail.text)]) {
      expect(body).toContain('첨부 파일이 커서 함께 전달하지 못했습니다');
      expect(body).toContain('guide.pdf');
      expect(body).toContain('보낸 사람에게 파일을 다시 요청해 주세요');
      expect(body).not.toContain('Resend');
      expect(body).not.toContain('수신 목록');
    }
    expect(String(mail.text).endsWith('확인했습니다')).toBe(true);
  });
});
