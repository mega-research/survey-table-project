/**
 * 답장 중계 규칙 — 중계 주소 만들기·풀기, 자동 메일 판정, 응답자에게 넘기는 메일의 모양.
 *
 * 서명은 진짜(HMAC-SHA256)를 쓴다. 기대값은 코드가 아니라 openssl 로 따로 계산한 글자다:
 *   printf '%s' 'reply-relay:v1:survey:kim@corp.co.kr' | openssl dgst -sha256 -hmac 'test-relay-secret'  → 앞 10자
 */
import { describe, expect, it } from 'vitest';

import { MAX_RECIPIENTS_PER_MAIL } from '@/lib/mail/split-email-addresses';

import { createRelaySigner } from '../services/reply-relay-signer';
import type { ReceivedReply } from './reply-forward';
import {
  RELAY_LOCAL_PART_MAX_LENGTH,
  buildRelayLocalPart,
  buildRelayMail,
  extractRelayTargets,
  hasReplyRelayTag,
  isAutoGeneratedMail,
  parseRelayAddress,
  readDmarcVerdict,
  relayTargetAddress,
  relayTargetKey,
} from './reply-relay';

const SEND_DOMAIN = 'send.example.co.kr';
const signer = createRelaySigner('test-relay-secret');

describe('buildRelayLocalPart — 중계 주소의 @ 앞', () => {
  it.each<[string, string, string, string]>([
    ['보낸이 계정 + 응답자 주소의 @ 앞 = 도메인 = 서명', 'survey', 'kim@corp.co.kr', 'survey+kim=corp.co.kr=42a7387e98'],
    ['티켓의 예와 같은 모양이다', 'lsjlc', 'hong@example.com', 'lsjlc+hong=example.com=47c8a45f33'],
    ['@ 앞에 = · + · . 이 든 주소도 그대로 싣는다', 'survey', 'a=b+c.d@corp.co.kr', 'survey+a=b+c.d=corp.co.kr=3988016757'],
    ['계정이 다르면 서명이 다르다', 'panel', 'kim@corp.co.kr', 'panel+kim=corp.co.kr=7904f0b204'],
    ['대문자는 그대로 싣고, 서명은 소문자로 만든 것과 같다', 'survey', 'Kim@Corp.co.kr', 'survey+Kim=Corp.co.kr=42a7387e98'],
  ])('%s', (_name, senderAccount, respondentAddress, expected) => {
    expect(buildRelayLocalPart({ senderAccount, respondentAddress, signer })).toBe(expected);
  });

  it('키가 다르면 서명이 다르다', () => {
    const other = createRelaySigner('other-secret');

    expect(buildRelayLocalPart({ senderAccount: 'survey', respondentAddress: 'kim@corp.co.kr', signer: other })).toBe(
      'survey+kim=corp.co.kr=81fe913ba9',
    );
  });

  it('@ 앞 전체가 64자면 만들고, 65자면 만들지 않는다', () => {
    // survey(6) + '+' + 응답자 @ 앞 + '=' + corp.co.kr(10) + '=' + 서명(10) = 29 + 응답자 @ 앞
    const fits = `${'a'.repeat(35)}@corp.co.kr`;
    const tooLong = `${'a'.repeat(36)}@corp.co.kr`;

    const built = buildRelayLocalPart({ senderAccount: 'survey', respondentAddress: fits, signer });
    expect(built).toHaveLength(RELAY_LOCAL_PART_MAX_LENGTH);
    expect(RELAY_LOCAL_PART_MAX_LENGTH).toBe(64);
    expect(buildRelayLocalPart({ senderAccount: 'survey', respondentAddress: tooLong, signer })).toBeNull();
  });

  it.each<[string, string]>([
    ['공백', 'kim lee@corp.co.kr'],
    ['따옴표로 감싼 @ 앞', '"kim"@corp.co.kr'],
    ['한글', '김응답@corp.co.kr'],
    ['한글 도메인', 'kim@회사.kr'],
    ['꺾쇠', 'kim<x>@corp.co.kr'],
    ['쉼표', 'kim,lee@corp.co.kr'],
    ['점으로 시작', '.kim@corp.co.kr'],
    ['점이 연달아', 'kim..lee@corp.co.kr'],
    ['도메인에 =', 'kim@corp=co.kr'],
    ['@ 가 없다', 'kim.corp.co.kr'],
    ['@ 앞이 비었다', '@corp.co.kr'],
    ['빈 글자', ''],
  ])('중계 주소로 옮길 수 없는 글자(%s)가 있으면 만들지 않는다', (_name, respondentAddress) => {
    expect(buildRelayLocalPart({ senderAccount: 'survey', respondentAddress, signer })).toBeNull();
  });
});

describe('parseRelayAddress — 중계 주소 풀기', () => {
  it.each<[string, string, { senderAccount: string; respondentAddress: string }]>([
    [
      '만든 그대로',
      'survey+kim=corp.co.kr=42a7387e98@send.example.co.kr',
      { senderAccount: 'survey', respondentAddress: 'kim@corp.co.kr' },
    ],
    [
      '오른쪽부터 끊는다 — @ 앞에 = · + 가 있어도 된다',
      'survey+a=b+c.d=corp.co.kr=3988016757@send.example.co.kr',
      { senderAccount: 'survey', respondentAddress: 'a=b+c.d@corp.co.kr' },
    ],
    [
      '메일 시스템이 주소를 통째로 대문자로 바꿔도 통과한다',
      'SURVEY+KIM=CORP.CO.KR=42A7387E98@SEND.EXAMPLE.CO.KR',
      { senderAccount: 'survey', respondentAddress: 'KIM@CORP.CO.KR' },
    ],
    [
      '응답자 주소의 대문자는 받은 그대로 돌려준다',
      'survey+Kim=Corp.co.kr=42a7387e98@send.example.co.kr',
      { senderAccount: 'survey', respondentAddress: 'Kim@Corp.co.kr' },
    ],
    [
      '꺾쇠로 감싼 주소도 읽는다',
      '<survey+kim=corp.co.kr=42a7387e98@send.example.co.kr>',
      { senderAccount: 'survey', respondentAddress: 'kim@corp.co.kr' },
    ],
  ])('%s', (_name, address, expected) => {
    expect(parseRelayAddress(address, SEND_DOMAIN, signer)).toEqual(expected);
  });

  it.each<[string, string]>([
    ['서명 위조', 'survey+kim=corp.co.kr=0000000000@send.example.co.kr'],
    ['서명 한 글자가 다르다', 'survey+kim=corp.co.kr=42a7387e99@send.example.co.kr'],
    ['잘린 서명', 'survey+kim=corp.co.kr=42a7387e9@send.example.co.kr'],
    ['서명이 길다', 'survey+kim=corp.co.kr=42a7387e98a@send.example.co.kr'],
    ['서명이 16진이 아니다', 'survey+kim=corp.co.kr=zzzzzzzzzz@send.example.co.kr'],
    ['다른 계정의 서명', 'panel+kim=corp.co.kr=42a7387e98@send.example.co.kr'],
    ['다른 응답자의 서명', 'survey+lee=corp.co.kr=42a7387e98@send.example.co.kr'],
    ['같은 @ 앞에 다른 도메인', 'survey+kim=evil.com=42a7387e98@send.example.co.kr'],
    ['서명이 없다', 'survey+kim=corp.co.kr@send.example.co.kr'],
    ['꼬리가 없다', 'survey@send.example.co.kr'],
    ['꼬리가 비었다', 'survey+@send.example.co.kr'],
    ['응답자의 @ 앞이 비었다', 'survey+=corp.co.kr=42a7387e98@send.example.co.kr'],
    ['계정이 비었다', '+kim=corp.co.kr=42a7387e98@send.example.co.kr'],
    ['발송 전용 도메인이 아니다', 'survey+kim=corp.co.kr=42a7387e98@other.example.co.kr'],
    ['@ 가 없다', 'survey+kim=corp.co.kr=42a7387e98'],
  ])('%s 은(는) 중계 주소가 아니다', (_name, address) => {
    expect(parseRelayAddress(address, SEND_DOMAIN, signer)).toBeNull();
  });

  it('키를 바꾸면 이미 나간 중계 주소는 풀리지 않는다', () => {
    const rotated = createRelaySigner('other-secret');

    expect(parseRelayAddress('survey+kim=corp.co.kr=42a7387e98@send.example.co.kr', SEND_DOMAIN, rotated)).toBeNull();
  });

  it('만든 주소는 그대로 풀린다 — 왕복', () => {
    for (const respondentAddress of ['kim@corp.co.kr', 'a=b+c.d@corp.co.kr', 'First.Last_1-2@Sub.Corp.co.kr']) {
      const localPart = buildRelayLocalPart({ senderAccount: 'survey', respondentAddress, signer });

      expect(localPart).not.toBeNull();
      expect(parseRelayAddress(`${localPart}@${SEND_DOMAIN}`, SEND_DOMAIN, signer)).toEqual({
        senderAccount: 'survey',
        respondentAddress,
      });
    }
  });
});

describe('extractRelayTargets — 받는 주소에서 서명이 맞는 중계 주소만', () => {
  it('서명이 맞는 것만, 받은 순서대로, 같은 응답자는 한 번만 돌려준다', () => {
    const targets = extractRelayTargets(
      [
        'boss@example.co.kr',
        'survey+kim=corp.co.kr=0000000000@send.example.co.kr',
        'survey+park=other.co.kr=74e0ba501b@send.example.co.kr',
        'survey@send.example.co.kr',
        'survey+kim=corp.co.kr=42a7387e98@send.example.co.kr',
        'SURVEY+KIM=CORP.CO.KR=42A7387E98@send.example.co.kr',
      ],
      SEND_DOMAIN,
      signer,
    );

    expect(targets).toEqual([
      { senderAccount: 'survey', respondentAddress: 'park@other.co.kr' },
      { senderAccount: 'survey', respondentAddress: 'kim@corp.co.kr' },
    ]);
  });

  it('응답자 주소가 발송 전용 도메인이면 빼 버린다 — 넘긴 메일이 다시 들어온다', () => {
    const localPart = buildRelayLocalPart({
      senderAccount: 'survey',
      respondentAddress: 'panel@send.example.co.kr',
      signer,
    });

    expect(extractRelayTargets([`${localPart}@${SEND_DOMAIN}`], SEND_DOMAIN, signer)).toEqual([]);
  });

  it('한 통의 수신자 상한을 넘으면 앞에서부터 남긴다', () => {
    const receivedFor = Array.from({ length: MAX_RECIPIENTS_PER_MAIL + 5 }, (_, index) => {
      const localPart = buildRelayLocalPart({
        senderAccount: 'survey',
        respondentAddress: `user${index}@corp.co.kr`,
        signer,
      });
      return `${localPart}@${SEND_DOMAIN}`;
    });

    const targets = extractRelayTargets(receivedFor, SEND_DOMAIN, signer);

    expect(targets).toHaveLength(MAX_RECIPIENTS_PER_MAIL);
    expect(targets[0]?.respondentAddress).toBe('user0@corp.co.kr');
  });
});

describe('relayTargetKey — 중계 메일의 멱등 키에 붙는 대상 조각', () => {
  // 기대값은 코드가 아니라 openssl 로 따로 계산한 글자다:
  //   printf '%s' 'reply-relay-target:v1:kim@corp.co.kr' | openssl dgst -sha256 -hmac 'test-relay-secret'  → 앞 10자
  it.each<[string, string, string]>([
    ['응답자 주소에서 뽑는다', 'kim@corp.co.kr', '84c37c0a92'],
    ['다른 응답자는 다른 조각이다', 'park@other.co.kr', '4158e183fe'],
    ['대소문자를 가리지 않는다 — 메일 시스템이 주소를 바꿔 돌려줘도 같은 대상이다', 'KIM@Corp.Co.KR', '84c37c0a92'],
  ])('%s', (_name, respondentAddress, expected) => {
    expect(relayTargetKey({ respondentAddress }, signer)).toBe(expected);
  });

  it('주소를 싣지 않고, 중계 주소의 서명과도 다른 값이다 — 키에서 주소도 서명도 읽히지 않는다', () => {
    const key = relayTargetKey({ respondentAddress: 'kim@corp.co.kr' }, signer);

    expect(key).toMatch(/^[0-9a-f]{10}$/);
    // 중계 주소 survey+kim=corp.co.kr=42a7387e98 의 서명.
    expect(key).not.toBe('42a7387e98');
  });

  it('키가 다르면 조각도 다르다', () => {
    expect(relayTargetKey({ respondentAddress: 'kim@corp.co.kr' }, createRelaySigner('other-secret'))).not.toBe(
      '84c37c0a92',
    );
  });
});

